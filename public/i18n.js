const LOCALES = { fi: 'fi-FI', vi: 'vi-VN', en: 'en-IE' };
let currentLang = 'fi';

function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || I18N.fi[key] || key;
}

function applyLang(lang) {
  if (!I18N[lang]) lang = 'fi';
  currentLang = lang;
  document.documentElement.lang = lang;
  document.title = t('meta.title');
  document.querySelector('meta[name="description"]').setAttribute('content', t('meta.desc'));

  document.querySelectorAll('[data-i18n]').forEach((el) => { el.innerHTML = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh);
    el.setAttribute('aria-label', el.placeholder);
  });
  document.querySelectorAll('.lang button').forEach((b) => {
    const on = b.dataset.lang === lang;
    b.classList.toggle('active', on);
    b.setAttribute('aria-pressed', on);
  });

  try { localStorage.setItem('vnl-lang', lang); } catch (e) {}
  if (window.onLangChange) window.onLangChange();
}

document.querySelectorAll('.lang button').forEach((b) =>
  b.addEventListener('click', () => applyLang(b.dataset.lang))
);

let initial = 'fi';
try { initial = localStorage.getItem('vnl-lang') || initial; } catch (e) {}
applyLang(initial);
